#!/usr/bin/env bash
# SPDX-License-Identifier: GPL-3.0-or-later
# Verify native RUN metadata and generic package without running boot-install.
set -euo pipefail

version="${1:?Usage: packaging/test-release.sh VERSION [OUTPUT_DIRECTORY]}"
out="${2:-dist}"
deb="$out/infiltrator-boot_${version}_amd64.deb"
run="$out/boot-$version-native-installer.run"

test -s "$deb"
test -s "$run"
test -s "$out/SHA256SUMS"
(cd "$out" && sha256sum -c SHA256SUMS)
test "$(dpkg-deb -f "$deb" Package)" = infiltrator-boot
test "$(dpkg-deb -f "$deb" Version)" = "$version"
test "$(dpkg-deb -f "$deb" Architecture)" = amd64

work=$(mktemp -d)
trap 'rm -rf -- "$work"' EXIT
dpkg-deb --contents "$deb" > "$work/package-files.txt"
grep -Fq 'usr/share/infiltrator-boot/boot/boot_x64.efi' "$work/package-files.txt"
grep -Fq 'usr/share/infiltrator-boot/docs/COPYING.txt' "$work/package-files.txt"
if grep -Eq 'usr/share/infiltrator-boot/(mvboot|boot-mkdefault)( |$)' "$work/package-files.txt"; then
    echo "Obsolete or Python-dependent helper was included" >&2; exit 1
fi
if grep -Eq 'usr/share/infiltrator-boot/docs/(LICENSE|CREDITS|NEWS)\.txt' "$work/package-files.txt"; then
    echo "Obsolete upstream text file was included in the BOOT package" >&2
    exit 1
fi
dpkg-deb --ctrl-tarfile "$deb" | tar -tf - > "$work/control.txt"
grep -Eq '^\./control$|^control$' "$work/control.txt"
if grep -Eq '(^|/)(postinst|preinst|prerm|postrm)$' "$work/control.txt"; then
    echo "Generic package unexpectedly runs firmware installation scripts" >&2
    exit 1
fi

# The RUN embeds the exact original boot-install implementation, while
# downloading ONLY BOOT's pinned build source. Never execute firmware writes
# in a packaging CI runner.
bash -n "$run"
bash -n boot-install
test "$(head -n 1 "$run")" = '#!/usr/bin/env bash'
test "$(stat -c '%s' "$run")" -lt 200000

# The embedded code must be byte-identical to the canonical boot-install.
awk '
    $0 == "# EMBEDDED_BOOT_INSTALL_BEGIN" { inside=1; next }
    $0 == "# EMBEDDED_BOOT_INSTALL_END" { exit }
    inside { print }
' "$run" > "$work/embedded-boot-install"
test -s "$work/embedded-boot-install"
cmp boot-install "$work/embedded-boot-install"
bash -n "$work/embedded-boot-install"

# The downloaded source revision must match the installer generated by CI.
expected=$(git rev-parse --verify HEAD)
grep -Fxq "SOURCE_SHA=\"$expected\"" "$run"
grep -Fxq "RELEASE_VERSION=\"$version\"" "$run"
grep -Fq -- '-DBOOT_RELEASE_VERSION=' "$run"
grep -Fq 'BOOT_SBAT_CSV=boot-sbat-release.csv' "$run"
grep -Fq "SOURCE_URL='https://github.com/Infiltrator-Projects/Boot.git'" "$run"
grep -Fq 'fetch --quiet --depth 1 --filter=blob:none origin "$SOURCE_SHA"' "$run"
grep -Fq 'rev-parse HEAD) == "$SOURCE_SHA"' "$run"
grep -Fq -- '-march=native -mtune=native -mgeneral-regs-only' "$run"
grep -Fq 'export BOOT_INSTALL_SOURCE_DIR="$source_dir"' "$run"
grep -Fq 'set +e +u' "$run"
grep -Fq 'embedded_boot_install --nodrivers' "$run"
if [[ $(grep -Ec '^embedded_boot_install --nodrivers$' "$run") != 1 ]]; then
    echo "BOOT RUN must invoke exactly one embedded installation" >&2
    exit 1
fi

# Validate the bootstrap only: embedded boot-install retains its own options.
awk '/^embedded_boot_install\(\) \{$/ { exit } { print }' "$run" > "$work/bootstrap"
if grep -Eq -- '--build-only|__BOOT_SOURCE_ARCHIVE_BELOW__|SOURCE_DIGEST=|base64 --decode|bash ./boot-install' "$work/bootstrap"; then
    echo "BOOT RUN must download build sources and execute embedded installer logic" >&2
    exit 1
fi

grep -Fq 'InstallationFailed=1' "$work/embedded-boot-install"
grep -Fq 'exit "$InstallationFailed"' "$work/embedded-boot-install"
grep -Fxq 'TargetDir=/EFI/InfiltratorOS/BOOT' "$work/embedded-boot-install"
grep -Fxq 'TargetX64="BOOTX64.EFI"' "$work/embedded-boot-install"
grep -Fq 'GuardDefaultBootLocation || return 1' "$work/embedded-boot-install"
grep -Fq 'Boot="$TargetX64"' "$work/embedded-boot-install"
grep -Fq 'BOOT_INSTALL_SOURCE_DIR' "$work/embedded-boot-install"
grep -A5 'create an ESP, and ideally boot in EFI mode, before installing BOOT.' "$work/embedded-boot-install" |
    grep -Fq 'exit 1'
test -s "$work/embedded-boot-install"
echo "Verified source-downloading RUN with full inline boot-install and generic DEB"
